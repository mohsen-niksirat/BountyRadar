window.BR_T = function (key) {
  const pack = window.BR_I18N[window.BR_LANG] || window.BR_I18N.en;
  return pack[key] != null ? pack[key] : (window.BR_I18N.en[key] != null ? window.BR_I18N.en[key] : key);
};
window.BR_SET_LANG = function (lang) {
  if (!window.BR_I18N[lang]) lang = "en";
  window.BR_LANG = lang;
  return lang;
};
